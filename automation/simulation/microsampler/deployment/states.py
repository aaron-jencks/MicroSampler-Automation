class MicroSamplerTCDataCollectionStage(DeploymentState):
    def execute(self, ctx: MicroSamplerTCLoopContext):
        run_config = ctx.context.run_config
        log_prefix = ctx.context.log_prefix
        key_name = ctx.context.current_key_name
        key_file = ctx.context.current_key_file
        executable = run_config.executable

        if log_prefix is None:
            ctx.stop(RuntimeError("log_prefix was not prepared"))
            return
        if key_name is None or key_file is None:
            ctx.stop(RuntimeError("generated key information is missing"))
            return
        if executable is None:
            ctx.stop(RuntimeError("deployed executable path is missing"))
            return

        simulation_trace = log_prefix / "out-all-asm.log.gz"
        parsed_state = log_prefix / "uarch.pickle"
        sets_file = log_prefix / "sets.pickle"
        stats_output = log_prefix / f"stats-{run_config.phi}_{run_config.alpha}.log"
        simulation_log = log_prefix / "launch_simulation.log"
        parse_log = log_prefix / "launch_parse.log"
        stats_log = log_prefix / "launch_stats.log"

        required_files = [
            key_file,
            executable,
            simulation_trace,
            parsed_state,
            sets_file,
            stats_output,
            simulation_log,
            parse_log,
            stats_log,
        ]
        missing_files = [path for path in required_files if not path.is_file()]
        if missing_files:
            ctx.stop(
                FileNotFoundError(
                    "required deployment artifacts are missing: "
                    + ", ".join(str(path) for path in missing_files)
                )
            )
            return

        if not stats_output.read_text(
            encoding="utf-8",
            errors="replace",
        ).strip():
            ctx.stop(ValueError(f"stats output is empty: {stats_output}"))
            return

        ctx.context.collected_data.append(
            MicroSamplerTCIterationResult(
                global_iteration=ctx.context.current_global_iteration,
                key_name=key_name,
                key_file=key_file,
                executable=executable,
                log_prefix=log_prefix,
                simulation_trace=simulation_trace,
                parsed_state=parsed_state,
                sets_file=sets_file,
                stats_output=stats_output,
                simulation_log=simulation_log,
                parse_log=parse_log,
                stats_log=stats_log,
            )
        )

        self.append_deployment_state(
            ctx,
            MicroSamplerTCDeploymentState.LOOP_CHECK,
        )
